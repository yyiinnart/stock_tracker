const fs=require('node:fs');
let html=fs.readFileSync('index.html','utf8');
html=html.replace('<link rel="stylesheet" href="interface.css">',()=>`<style>\n${fs.readFileSync('interface.css','utf8')}\n</style>`);
html=html.replace('<script src="setup-assets.js"></script>','');
for(const file of ['portfolio-core.js','enhancements.js','cloud-sync.js','interface.js'])html=html.replace(`<script src="${file}"></script>`,()=>`<script>\n${fs.readFileSync(file,'utf8')}\n</script>`);
fs.writeFileSync('apps-script/Index.html',html);
const files={server:fs.readFileSync('apps-script/Code.gs','utf8'),page:html};
fs.writeFileSync('setup-assets.js','/* Generated by node build-cloud.cjs; contains code only. */\nglobalThis.CLOUD_INSTALL_FILES='+JSON.stringify(files).replace(/</g,'\\u003c')+';\n');
